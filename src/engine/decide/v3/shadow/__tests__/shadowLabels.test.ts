/**
 * 05.4-42 (D-10, D-16): scripts/shadow-labels.json maps every `code|variant|once` a shadow row can carry to the chip text the app
 * shows for it, so the shadow report (a plain .mjs script that cannot import the engine) names answers the way the app does.
 * once = 1 for the one-off cash samples (s60, p500, l2000, c9000_cash), 0 for the two plan samples; verdictRowFor reads "tight"
 * differently for each. This test rebuilds the map from verdictRowFor and en.ts and fails on any drift. After a copy or verdict
 * table change:
 *   SHADOW_LABELS_WRITE=1 npx jest src/engine/decide/v3/shadow/__tests__/shadowLabels.test.ts
 */
import * as fs from 'fs';
import * as path from 'path';
import en from '../../../../../i18n/locales/en';
import { VARIANTS } from '../../__tests__/rightAnswers/schema';
import { CODE_PRECEDENCE } from '../../constants';
import { verdictRowFor } from '../../copy/verdictTable';
import type { Variant } from '../../types';

const FILE = path.join(__dirname, '../../../../../../scripts/shadow-labels.json');

function lookup(key: string): string {
  let node: unknown = en;
  for (const part of key.split('.')) node = (node as Record<string, unknown>)[part];
  if (typeof node !== 'string') throw new Error(`no copy for ${key}`);
  return node;
}

function build(): Record<string, string> {
  const labels: Record<string, string> = {};
  for (const code of CODE_PRECEDENCE) {
    for (const variant of [null, ...VARIANTS] as (Variant | null)[]) {
      for (const once of [true, false]) {
        labels[`${code}|${variant ?? ''}|${once ? 1 : 0}`] = lookup(verdictRowFor(code, variant, once).chipKey);
      }
    }
  }
  return labels;
}

describe('shadow report labels (05.4-42)', () => {
  const built = build();

  if (process.env.SHADOW_LABELS_WRITE === '1') {
    it('writes scripts/shadow-labels.json', () => {
      const body = { note: '05.4-42: code|variant|once -> app chip text. Generated by shadowLabels.test.ts; do not edit.', labels: built };
      fs.writeFileSync(FILE, `${JSON.stringify(body, null, 2)}\n`);
      expect(fs.existsSync(FILE)).toBe(true);
    });
    return;
  }

  it('scripts/shadow-labels.json matches verdictRowFor and en.ts (run SHADOW_LABELS_WRITE=1 after a copy change)', () => {
    const file = JSON.parse(fs.readFileSync(FILE, 'utf8')) as { labels: Record<string, string> };
    expect(file.labels).toEqual(built);
  });

  it('covers every code and variant, one-off and plan, with chip text that has no placeholder', () => {
    expect(Object.keys(built)).toHaveLength(CODE_PRECEDENCE.length * (VARIANTS.length + 1) * 2);
    for (const text of Object.values(built)) {
      expect(text.length).toBeGreaterThan(0);
      expect(text).not.toMatch(/\{\{/);
    }
  });

  it('tells one-off tight from plan tight, as the app does', () => {
    expect(built['fits_month|tight|1']).toBe(lookup(verdictRowFor('fits_month', 'tight', true).chipKey));
    expect(built['fits_month|tight|0']).toBe(lookup(verdictRowFor('fits_month', 'tight', false).chipKey));
    expect(built['fits_month|tight|1']).not.toBe(built['fits_month|tight|0']);
  });
});
